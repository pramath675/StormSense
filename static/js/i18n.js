let currentLanguage = "en";

function setLanguage(lang) {
    if (!I18N_TRANSLATIONS[lang]) return;
    currentLanguage = lang;
    localStorage.setItem("cyclone_lang", lang);

    // Update active button state
    document.querySelectorAll(".lang-btn").forEach(btn => {
        if (btn.getAttribute("data-lang") === lang) {
            btn.classList.add("active-lang");
        } else {
            btn.classList.remove("active-lang");
        }
    });

    // Translate all elements with data-i18n attribute
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        const val = I18N_TRANSLATIONS[lang][key];
        if (val) {
            if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
                el.placeholder = val;
            } else {
                el.textContent = val;
            }
        }
    });

    // Fire custom event for dynamic components (charts, storm list, modals)
    document.dispatchEvent(new CustomEvent("languageChanged", { detail: { lang } }));
}

function t(key) {
    return (I18N_TRANSLATIONS[currentLanguage] && I18N_TRANSLATIONS[currentLanguage][key]) || key;
}

// Initialize on DOM load
document.addEventListener("DOMContentLoaded", () => {
    const saved = localStorage.getItem("cyclone_lang") || "en";
    setLanguage(saved);
});
